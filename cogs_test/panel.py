    @app_commands.context_menu(name="Save to Panels")
    async def save_message(self, interaction: discord.Interaction, message: discord.Message):
        try:
            if interaction.guild_id is None:
                await interaction.response.send_message("This action is only available in a server.", ephemeral=True)
                return
            images = [a for a in message.attachments if (a.content_type or "").startswith("image/")]
            if not images:
                await interaction.response.send_message("That message has no image attachments.", ephemeral=True)
                return
            # Pre-fill the source message URL. The add modal handles a single upload;
            # users can select the attachment URL as the source and re-upload it manually.
            await interaction.response.send_message(
                "Open /panels → Add Panel and upload the image from this message. Source message: " + message.jump_url,
                ephemeral=True,
            )
        except Exception:
            log.exception("Save to Panels context menu failed")
            if interaction.response.is_done():
                await interaction.followup.send("Something went wrong.", ephemeral=True)
            else:
                await interaction.response.send_message("Something went wrong.", ephemeral=True)


