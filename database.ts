export async function initDatabase(config: DatabaseConfig): Promise<void> {
  if (!pool) pool = createDatabasePool(config);
  const activePool = databasePool();
  await activePool.query("SELECT 1");
  const client = await activePool.connect();
  try {
    await client.query("BEGIN");
    for (const statement of schemaStatements) await client.query(statement);

    await client.query("ALTER TABLE users ADD COLUMN IF NOT EXISTS guild_id BIGINT");
    const usersWithoutGuild = await client.query<{ count: string }>(
      "SELECT COUNT(*)::text AS count FROM users WHERE guild_id IS NULL",
    );
    if (Number(usersWithoutGuild.rows[0]?.count ?? 0) > 0) {
      if (!config.primaryGuildId) {
        throw new Error("GUILD_ID or PRIMARY_GUILD_ID must be configured to safely assign existing users that have no guild_id.");
      }
      await client.query("UPDATE users SET guild_id = $1 WHERE guild_id IS NULL", [config.primaryGuildId]);
    }
    const userIdentifierColumns = await client.query<{ column_name: string; data_type: string }>(
      `SELECT column_name, data_type FROM information_schema.columns
       WHERE table_schema = current_schema() AND table_name = 'users'
         AND column_name = ANY($1::text[])`,
      [["discord_id", "guild_id", "anilist_id"]],
    );
    for (const column of userIdentifierColumns.rows) {
      if (column.data_type !== "bigint") {
        await client.query(
          `ALTER TABLE users ALTER COLUMN ${column.column_name} TYPE BIGINT USING ${column.column_name}::BIGINT`,
        );
      }
    }
    await client.query("ALTER TABLE users ALTER COLUMN guild_id SET NOT NULL");

    const userUniqueConstraints = await client.query<{ constraint_name: string }>(
      `SELECT constraint_name FROM information_schema.table_constraints
       WHERE table_schema = current_schema() AND table_name = 'users'
         AND constraint_type = 'UNIQUE'`,
    );
    let hasGuildScopedUserKey = false;
    for (const constraint of userUniqueConstraints.rows) {
      const columns = await client.query<{ column_name: string; ordinal_position: number }>(
        `SELECT column_name, ordinal_position FROM information_schema.key_column_usage
         WHERE table_schema = current_schema() AND table_name = 'users' AND constraint_name = $1
         ORDER BY ordinal_position`,
        [constraint.constraint_name],
      );
      const key = columns.rows.map(row => row.column_name).join(",");
      if (key === "discord_id") {
        const safeName = constraint.constraint_name.replaceAll('"', '""');
        await client.query(`ALTER TABLE users DROP CONSTRAINT "${safeName}"`);
      } else if (key === "discord_id,guild_id") {
        hasGuildScopedUserKey = true;
      }
    }
    if (!hasGuildScopedUserKey) {
      await client.query("ALTER TABLE users ADD CONSTRAINT users_discord_guild_unique UNIQUE (discord_id, guild_id)");
    }

    const legacyGuildSettings = await client.query<{ column_name: string }>(
      `SELECT column_name FROM information_schema.columns
       WHERE table_schema = current_schema() AND table_name = 'guild_settings'
         AND column_name = ANY($1::text[])`,
      [["guild_id", "panel_storage_channel_id", "panel_log_channel_id", "panel_mod_role_id", "archive_scope"]],
    );
    const legacyGuildColumns = new Set(legacyGuildSettings.rows.map(row => row.column_name));
    if (legacyGuildColumns.has("guild_id")) {
      const legacySettingColumn = (column: string): string =>
        legacyGuildColumns.has(column) ? column : "NULL::BIGINT";
      await client.query(
        `INSERT INTO guild_archive_settings (guild_id, moderation_channel_id, moderator_role_id, legacy_storage_channel_id)
         SELECT guild_id, ${legacySettingColumn("panel_log_channel_id")}, ${legacySettingColumn("panel_mod_role_id")}, ${legacySettingColumn("panel_storage_channel_id")}
           FROM guild_settings
          WHERE ${legacySettingColumn("panel_log_channel_id")} IS NOT NULL
             OR ${legacySettingColumn("panel_mod_role_id")} IS NOT NULL
             OR ${legacySettingColumn("panel_storage_channel_id")} IS NOT NULL
         ON CONFLICT (guild_id) DO UPDATE SET
           moderation_channel_id = COALESCE(guild_archive_settings.moderation_channel_id, EXCLUDED.moderation_channel_id),
           moderator_role_id = COALESCE(guild_archive_settings.moderator_role_id, EXCLUDED.moderator_role_id),
           legacy_storage_channel_id = COALESCE(guild_archive_settings.legacy_storage_channel_id, EXCLUDED.legacy_storage_channel_id)`,
      );
    }

    const legacyPanelsTable = await client.query<{ exists: boolean }>(
      "SELECT to_regclass('panels') IS NOT NULL AS exists",
    );
    if (legacyPanelsTable.rows[0]?.exists) {
      await client.query(
        "CREATE UNIQUE INDEX IF NOT EXISTS community_archive_legacy_panel_idx ON community_archive_entries (source_legacy_panel_id) WHERE source_legacy_panel_id IS NOT NULL",
      );
      const legacyPanelColumns = await client.query<{ column_name: string }>(
        `SELECT column_name FROM information_schema.columns
         WHERE table_schema = current_schema() AND table_name = 'panels'`,
      );
      const availablePanelColumns = new Set(legacyPanelColumns.rows.map(row => row.column_name));
      const requiredPanelColumns = ["id", "uploader_id", "uploader_guild_id", "filename", "title", "created_at"];
      if (requiredPanelColumns.every(column => availablePanelColumns.has(column))) {
        const hasPanelTags = await client.query<{ exists: boolean }>(
          "SELECT to_regclass('panel_tags') IS NOT NULL AS exists",
        );
        const tagsExpression = hasPanelTags.rows[0]?.exists
          ? "COALESCE((SELECT json_agg(tag ORDER BY tag)::text FROM panel_tags WHERE panel_id = p.id), '[]')"
          : "'[]'";
        const archiveScopeExpression = legacyGuildColumns.has("archive_scope")
          ? "CASE WHEN LOWER(COALESCE(gs.archive_scope, 'global')) = 'global' THEN 'global' ELSE 'server' END"
          : "'global'";
        const guildSettingsJoin = legacyGuildColumns.has("guild_id") && legacyGuildColumns.has("archive_scope")
          ? "LEFT JOIN guild_settings gs ON gs.guild_id = p.uploader_guild_id"
          : "";
        const optionalPanelColumn = (column: string, fallback: string) =>
          availablePanelColumns.has(column) ? "p." + column : fallback;
        const nsfwFilter = availablePanelColumns.has("is_nsfw") ? "AND COALESCE(p.is_nsfw, FALSE) = FALSE" : "";
        const importResult = await client.query(
          `INSERT INTO community_archive_entries (
             archive_type, title, content, media_type, source_url, tags, spoiler, status,
             created_by, created_guild_id, visibility, media_asset_id, attachment_filename,
             attachment_content_type, attachment_url, storage_message_id, storage_channel_id,
             chapter_number, linked_media_provider, linked_media_id, source_legacy_panel_id, created_at
           )
           SELECT
             'panels', LEFT(p.title, 200), COALESCE(${optionalPanelColumn("caption", "''")}, ''),
             'Manga',
             CASE WHEN ${optionalPanelColumn("source_url", "NULL")} LIKE 'https://%' THEN ${optionalPanelColumn("source_url", "NULL")} ELSE NULL END,
             ${tagsExpression}, FALSE, 'approved', p.uploader_id, COALESCE(p.uploader_guild_id, $1),
             ${archiveScopeExpression},
             ${optionalPanelColumn("media_asset_id", "NULL")},
             ${optionalPanelColumn("filename", "NULL")}, NULL,
             CASE WHEN ${optionalPanelColumn("attachment_url", "NULL")} LIKE 'https://%' THEN ${optionalPanelColumn("attachment_url", "NULL")} ELSE NULL END,
             ${optionalPanelColumn("storage_message_id", "NULL")},
             ${optionalPanelColumn("storage_channel_id", "NULL")},
             ${optionalPanelColumn("chapter_number", "NULL")},
             CASE WHEN ${optionalPanelColumn("anilist_id", "NULL")} IS NOT NULL THEN 'anilist' ELSE NULL END,
             ${optionalPanelColumn("anilist_id", "NULL")}::text, p.id, p.created_at
           FROM panels p
           ${guildSettingsJoin}
           WHERE COALESCE(p.uploader_guild_id, $1) IS NOT NULL
             ${nsfwFilter}
           ON CONFLICT (source_legacy_panel_id) WHERE source_legacy_panel_id IS NOT NULL DO NOTHING`,
          [config.primaryGuildId],
        );
        if (importResult.rowCount) {
          logger.info("Imported legacy Manga Panels into the unified Archive", { imported: importResult.rowCount });
        }
        if (!config.primaryGuildId) {
          const unassigned = await client.query<{ count: string }>(
            "SELECT COUNT(*)::text AS count FROM panels WHERE uploader_guild_id IS NULL",
          );
          if (Number(unassigned.rows[0]?.count ?? 0) > 0) {
            logger.warn("Legacy Panels without a source guild were left in the original table; configure GUILD_ID to migrate them safely", {
              skipped: Number(unassigned.rows[0]?.count ?? 0),
            });
          }
        }
        if (availablePanelColumns.has("is_nsfw")) {
          const excluded = await client.query<{ count: string }>(
            "SELECT COUNT(*)::text AS count FROM panels WHERE is_nsfw = TRUE",
          );
          if (Number(excluded.rows[0]?.count ?? 0) > 0) {
            logger.warn("NSFW legacy Panels were retained in the original table and not exposed in the unified Archive", {
              excluded: Number(excluded.rows[0]?.count ?? 0),
            });
          }
        }
      } else {
        logger.warn("Legacy panels table has an incomplete schema; records were left in place and not imported");
      }
    }


    const legacyBracketTable = await client.query<{ exists: boolean }>(
      "SELECT to_regclass('community_media_brackets') IS NOT NULL AS exists",
    );
    if (legacyBracketTable.rows[0]?.exists) {
      const legacyBrackets = await client.query<{
        bracket_id: string; guild_id: string; creator_id: string; title: string;
        media_type: string; candidates: string; status: string; created_at: Date;
      }>(
        "SELECT bracket_id, guild_id, creator_id, title, media_type, candidates, status, created_at FROM community_media_brackets",
      );
      const hasLegacyBracketVotes = (await client.query<{ exists: boolean }>(
        "SELECT to_regclass('community_media_bracket_votes') IS NOT NULL AS exists",
      )).rows[0]?.exists ?? false;
      for (const bracket of legacyBrackets.rows) {
        let candidates: string[];
        try {
          const parsed: unknown = JSON.parse(bracket.candidates);
          if (!Array.isArray(parsed) || parsed.length < 2 || parsed.length > 16
            || parsed.some(item => typeof item !== "string" || !item.trim() || item.length > 150)) {
            throw new Error("Invalid bracket candidates");
          }
          candidates = [...new Map((parsed as string[]).map(item => [item.trim().toLocaleLowerCase("en-US"), item.trim()])).values()];
          if (candidates.length < 2) throw new Error("Bracket candidates are not distinct");
        } catch {
          logger.warn("Legacy media bracket was skipped because its candidate list is invalid", {
            bracketId: bracket.bracket_id, guildId: bracket.guild_id,
          });
          continue;
        }
        const legacyKey = "media-bracket:" + bracket.bracket_id;
        const inserted = await client.query<{ id: string }>(
          `INSERT INTO community_rankings
             (guild_id, creator_id, title, description, status, legacy_source_key, created_at)
           VALUES ($1, $2, $3, $4, $5, $6, $7)
           ON CONFLICT (legacy_source_key) WHERE legacy_source_key IS NOT NULL DO NOTHING
           RETURNING id`,
          [
            bracket.guild_id, bracket.creator_id, bracket.title.slice(0, 180),
            "Imported media bracket · " + bracket.media_type.slice(0, 80),
            bracket.status === "closed" ? "closed" : "open", legacyKey, bracket.created_at,
          ],
        );
        const rankingId = inserted.rows[0]?.id;
        if (!rankingId) continue;
        for (const title of candidates) {
          await client.query(
            `INSERT INTO community_ranking_candidates
               (ranking_id, title, submitted_by, status, created_at)
             VALUES ($1, $2, $3, 'approved', $4)
             ON CONFLICT (ranking_id, title) DO NOTHING`,
            [rankingId, title, bracket.creator_id, bracket.created_at],
          );
        }
        if (hasLegacyBracketVotes) {
          const votes = await client.query<{
            user_id: string; candidate: string; updated_at: Date;
          }>(
            "SELECT user_id, candidate, updated_at FROM community_media_bracket_votes WHERE guild_id = $1 AND bracket_id = $2",
            [bracket.guild_id, bracket.bracket_id],
          );
          for (const vote of votes.rows) {
            await client.query(
              `INSERT INTO community_ranking_votes (ranking_id, user_id, candidate_id, updated_at)
               SELECT $1, $2, id, $4 FROM community_ranking_candidates
                WHERE ranking_id = $1 AND LOWER(title) = LOWER($3)
               ON CONFLICT (ranking_id, user_id) DO NOTHING`,
              [rankingId, vote.user_id, vote.candidate, vote.updated_at],
            );
          }
        }
      }
    }

    const legacyAdaptationTable = await client.query<{ exists: boolean }>(
      "SELECT to_regclass('community_adaptation_polls') IS NOT NULL AS exists",
    );
    if (legacyAdaptationTable.rows[0]?.exists) {
      const legacyPolls = await client.query<{
        poll_id: string; guild_id: string; creator_id: string; title: string;
        media_type: string; option_a: string; option_b: string; source_url: string | null; created_at: Date;
      }>(
        "SELECT poll_id, guild_id, creator_id, title, media_type, option_a, option_b, source_url, created_at FROM community_adaptation_polls",
      );
      const hasLegacyAdaptationVotes = (await client.query<{ exists: boolean }>(
        "SELECT to_regclass('community_adaptation_votes') IS NOT NULL AS exists",
      )).rows[0]?.exists ?? false;
      for (const poll of legacyPolls.rows) {
        if (!poll.option_a.trim() || !poll.option_b.trim()
          || poll.option_a.trim().toLocaleLowerCase("en-US") === poll.option_b.trim().toLocaleLowerCase("en-US")) {
          logger.warn("Legacy adaptation poll was skipped because its options are invalid", {
            pollId: poll.poll_id, guildId: poll.guild_id,
          });
          continue;
        }
        let sourceLink = "";
        if (poll.source_url) {
          try {
            const url = new URL(poll.source_url);
            if (url.protocol === "https:" && url.hostname && !url.username && !url.password) {
              sourceLink = "\nSource metadata: " + url.toString();
            }
          } catch {
            // Preserve the poll but omit an invalid optional source link.
          }
        }
        const legacyKey = "adaptation-poll:" + poll.poll_id;
        const inserted = await client.query<{ id: string }>(
          `INSERT INTO community_rankings
             (guild_id, creator_id, title, description, status, legacy_source_key, created_at)
           VALUES ($1, $2, $3, $4, 'open', $5, $6)
           ON CONFLICT (legacy_source_key) WHERE legacy_source_key IS NOT NULL DO NOTHING
           RETURNING id`,
          [
            poll.guild_id, poll.creator_id, poll.title.slice(0, 180),
            "Imported adaptation poll · " + poll.media_type.slice(0, 80) + sourceLink,
            legacyKey, poll.created_at,
          ],
        );
        const rankingId = inserted.rows[0]?.id;
        if (!rankingId) continue;
        const options = [poll.option_a.trim(), poll.option_b.trim()];
        for (const title of options) {
          await client.query(
            `INSERT INTO community_ranking_candidates
               (ranking_id, title, submitted_by, status, created_at)
             VALUES ($1, $2, $3, 'approved', $4)
             ON CONFLICT (ranking_id, title) DO NOTHING`,
            [rankingId, title.slice(0, 200), poll.creator_id, poll.created_at],
          );
        }
        if (hasLegacyAdaptationVotes) {
          const votes = await client.query<{ user_id: string; choice: string; updated_at: Date }>(
            "SELECT user_id, choice, updated_at FROM community_adaptation_votes WHERE guild_id = $1 AND poll_id = $2",
            [poll.guild_id, poll.poll_id],
          );
          for (const vote of votes.rows) {
            const selected = vote.choice.toUpperCase() === "A" ? options[0] : vote.choice.toUpperCase() === "B" ? options[1] : null;
            if (!selected) continue;
            await client.query(
              `INSERT INTO community_ranking_votes (ranking_id, user_id, candidate_id, updated_at)
               SELECT $1, $2, id, $4 FROM community_ranking_candidates
                WHERE ranking_id = $1 AND LOWER(title) = LOWER($3)
               ON CONFLICT (ranking_id, user_id) DO NOTHING`,
              [rankingId, vote.user_id, selected.slice(0, 200), vote.updated_at],
            );
          }
        }
      }
    }


    const legacyMangaChannels = await client.query<{ exists: boolean }>(
      "SELECT to_regclass('guild_manga_channels') IS NOT NULL AS exists",
    );
    if (legacyMangaChannels.rows[0]?.exists) {
      const imported = await client.query(
        `INSERT INTO media_notification_settings
           (guild_id, channel_id, enabled, include_anime, include_manga, updated_at)
         SELECT guild_id::BIGINT, channel_id::BIGINT, TRUE, TRUE, TRUE, NOW()
           FROM guild_manga_channels
          WHERE length(guild_id::text) BETWEEN 17 AND 20
            AND guild_id::text !~ '[^0-9]'
            AND length(channel_id::text) BETWEEN 17 AND 20
            AND channel_id::text !~ '[^0-9]'
         ON CONFLICT (guild_id) DO NOTHING`,
      );
      if (imported.rowCount) {
        logger.info("Imported existing per-server AniManga completion channels into media notifications", { imported: imported.rowCount });
      }
    }
    const legacyQuizTable = await client.query<{ exists: boolean }>(
      "SELECT to_regclass('community_media_quiz_questions') IS NOT NULL AS exists",
    );
    if (legacyQuizTable.rows[0]?.exists) {
      const legacyQuizRows = await client.query<{
        id: string; guild_id: string; creator_id: string;
        question: string; answer: string; source_url: string | null; created_at: Date;
      }>(
        "SELECT id, guild_id, creator_id, question, answer, source_url, created_at FROM community_media_quiz_questions ORDER BY guild_id, id",
      );
      const byGuild = new Map<string, typeof legacyQuizRows.rows>();
      let skippedQuizQuestions = 0;
      for (const row of legacyQuizRows.rows) {
        let sourceUrl: string | null = null;
        try {
          if (row.source_url) {
            const parsed = new URL(row.source_url);
            if (parsed.protocol === "https:" && parsed.hostname && !parsed.username && !parsed.password) {
              sourceUrl = parsed.toString();
            }
          }
        } catch {
          // Keep the original row in its source table; don't import a malformed link.
        }
        const question = row.question.trim();
        const answer = row.answer.trim();
        if (!sourceUrl || question.length < 10 || question.length > 500 || !answer || answer.length > 200) {
          skippedQuizQuestions += 1;
          continue;
        }
        const rows = byGuild.get(row.guild_id) ?? [];
        rows.push({ ...row, source_url: sourceUrl, question, answer });
        byGuild.set(row.guild_id, rows);
      }
      for (const [guildId, questions] of byGuild) {
        const legacyKey = "media-quiz:" + guildId;
        const first = questions[0]!;
        const insertedPack = await client.query<{ id: string }>(
          `INSERT INTO community_quiz_packs
             (guild_id, creator_id, title, description, mode, status, legacy_import_key, created_at)
           VALUES ($1, $2, 'Imported Media Quiz', 'Migrated from the previous server quiz pool. Questions require moderator review before play.', 'trivia', 'pending', $3, $4)
           ON CONFLICT (legacy_import_key) WHERE legacy_import_key IS NOT NULL DO NOTHING
           RETURNING id`,
          [guildId, first.creator_id, legacyKey, first.created_at],
        );
        const packId = insertedPack.rows[0]?.id ?? (
          await client.query<{ id: string }>(
            "SELECT id FROM community_quiz_packs WHERE legacy_import_key = $1",
            [legacyKey],
          )
        ).rows[0]?.id;
        if (!packId) throw new Error("The imported Media Quiz pack could not be resolved.");
        let importedCount = 0;
        for (const question of questions) {
          const insertedQuestion = await client.query(
            `INSERT INTO community_quiz_questions
               (pack_id, contributor_id, question, correct_answer, source_url, status, source_legacy_question_id, created_at)
             VALUES ($1, $2, $3, $4, $5, 'pending', $6, $7)
             ON CONFLICT (source_legacy_question_id) WHERE source_legacy_question_id IS NOT NULL DO NOTHING`,
            [packId, question.creator_id, question.question, question.answer, question.source_url, question.id, question.created_at],
          );
          importedCount += insertedQuestion.rowCount ?? 0;
        }
        if (importedCount) {
          logger.info("Imported source-backed legacy Media Quiz questions for moderator review", {
            guildId, packId, imported: importedCount,
          });
        }
      }
      if (skippedQuizQuestions) {
        logger.warn("Legacy Media Quiz questions without a valid HTTPS source or within the new question limits were retained in the original table and not imported", {
          skipped: skippedQuizQuestions,
        });
      }
    }

    const legacySnowflakeColumns = [
      ["bot_moderators", ["discord_id", "added_by"]],
      ["custom_role_records", ["guild_id", "user_id", "role_id", "icon_source_asset_id"]],
      ["custom_role_guild_settings", ["guild_id", "anchor_role_id", "command_channel_id", "log_channel_id"]],
      ["custom_role_pending_removals", ["guild_id", "log_channel_id", "log_message_id", "resolved_by"]],
      ["custom_role_archive_snoozes", ["guild_id", "user_id"]],
    ] as const;
    for (const [table, columns] of legacySnowflakeColumns) {
      const existingColumns = await client.query<{ column_name: string; data_type: string }>(
        `SELECT column_name, data_type FROM information_schema.columns
         WHERE table_schema = current_schema() AND table_name = $1 AND column_name = ANY($2::text[])`,
        [table, [...columns]],
      );
      for (const column of existingColumns.rows) {
        if (column.data_type !== "bigint") {
          await client.query(
            `ALTER TABLE ${table} ALTER COLUMN ${column.column_name} TYPE BIGINT USING ${column.column_name}::BIGINT`,
          );
        }
      }
    }

    const pendingUserIdsColumn = await client.query<{ data_type: string }>(
      `SELECT data_type FROM information_schema.columns
       WHERE table_schema = current_schema() AND table_name = 'custom_role_pending_removals'
         AND column_name = 'user_ids'`,
    );
    const pendingUserIdsType = pendingUserIdsColumn.rows[0]?.data_type;
    if (pendingUserIdsType && pendingUserIdsType !== "jsonb") {
      await client.query(
        "ALTER TABLE custom_role_pending_removals ALTER COLUMN user_ids DROP DEFAULT",
      );
      await client.query(
        `ALTER TABLE custom_role_pending_removals
         ALTER COLUMN user_ids TYPE JSONB
         USING CASE
           WHEN user_ids IS NULL OR BTRIM(user_ids::text) = '' THEN '[]'::JSONB
           ELSE user_ids::text::JSONB
         END`,
      );
      await client.query(
        "ALTER TABLE custom_role_pending_removals ALTER COLUMN user_ids SET DEFAULT '[]'::JSONB",
      );
      logger.info("Existing Custom Roles pending-removal records migrated to JSONB");
    }

    const existingRoleColumns = await client.query<{ column_name: string; data_type: string }>(
      `SELECT column_name, data_type FROM information_schema.columns
       WHERE table_schema = current_schema() AND table_name = 'booster_roles'
         AND column_name = ANY($1::text[])`,
      [["discord_id", "guild_id", "role_id"]],
    );
    if (existingRoleColumns.rows.length === 3) {
      const types = new Map(existingRoleColumns.rows.map(row => [row.column_name, row.data_type]));
      for (const column of ["discord_id", "guild_id", "role_id"] as const) {
        if (types.get(column) !== "bigint") {
          await client.query(
            `ALTER TABLE booster_roles ALTER COLUMN ${column} TYPE BIGINT USING ${column}::BIGINT`,
          );
        }
      }
      logger.info("Existing booster role identifiers widened to BIGINT for Discord snowflakes");
    } else if (existingRoleColumns.rows.length > 0) {
      logger.warn("Existing booster_roles table is incomplete; its records were not changed");
    }

    const missingGuildRows = await client.query<{ count: string }>(
      "SELECT COUNT(*)::text AS count FROM steam_users WHERE guild_id IS NULL",
    );
    if (Number(missingGuildRows.rows[0]?.count ?? 0) > 0) {
      if (!config.primaryGuildId) {
        throw new Error("GUILD_ID or PRIMARY_GUILD_ID must be configured to safely assign existing Steam links that have no guild_id.");
      }
      await client.query("UPDATE steam_users SET guild_id = $1 WHERE guild_id IS NULL", [config.primaryGuildId]);
    }
    await client.query("ALTER TABLE steam_users ALTER COLUMN discord_id TYPE BIGINT");
    await client.query("ALTER TABLE steam_users ALTER COLUMN guild_id TYPE BIGINT");
    await client.query("ALTER TABLE steam_users ALTER COLUMN guild_id SET NOT NULL");

    const primaryKey = await client.query<{ constraint_name: string }>(
      `SELECT constraint_name FROM information_schema.table_constraints
       WHERE table_schema = current_schema() AND table_name = 'steam_users'
         AND constraint_type = 'PRIMARY KEY' LIMIT 1`,
    );
    const keyName = primaryKey.rows[0]?.constraint_name;
    let hasGuildComposite = false;
    if (keyName) {
      const columns = await client.query<{ column_name: string; ordinal_position: number }>(
        `SELECT column_name, ordinal_position FROM information_schema.key_column_usage
         WHERE table_schema = current_schema() AND table_name = 'steam_users' AND constraint_name = $1
         ORDER BY ordinal_position`,
        [keyName],
      );
      hasGuildComposite = columns.rows.map((row) => row.column_name).join(",") === "discord_id,guild_id";
      if (!hasGuildComposite) {
        const safeKeyName = keyName.replaceAll('"', '""');
        await client.query(`ALTER TABLE steam_users DROP CONSTRAINT "${safeKeyName}"`);
      }
    }
    if (!hasGuildComposite) {
      await client.query("ALTER TABLE steam_users ADD CONSTRAINT steam_users_discord_guild_pk PRIMARY KEY (discord_id, guild_id)");
    }
    await client.query("CREATE INDEX IF NOT EXISTS steam_users_guild_lookup_idx ON steam_users (guild_id, discord_id)");
    await client.query("COMMIT");
    logger.info("PostgreSQL connected and v3 feature schema verified");
  } catch (error) {
    await client.query("ROLLBACK");
    logger.error("PostgreSQL schema initialization failed", {
      reason: error instanceof Error ? error.message : "Unknown error",
    });
    throw error;
  } finally {
    client.release();
  }
}

export async function closeDatabase(): Promise<void> {
  if (!pool) return;
  const activePool = pool;
  pool = undefined;
  await activePool.end();
}
