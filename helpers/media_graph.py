"""Shared PostgreSQL-backed relationship graph for Lemegeton's media systems.

Provider-declared relationships and provider recommendations are stored with distinct
provenance. Community-approved links are always scoped to the guild that approved them.
Community archives and panels remain in their existing tables and are joined at read time.
"""
from __future__ import annotations

import asyncio
import json
import logging
import re
from urllib.parse import urlsplit

import database
from helpers import media_storage

log = logging.getLogger("Lemegeton.MediaGraph")
_SCHEMA_READY = False
_SCHEMA_LOCK = asyncio.Lock()
GRAPH_SOURCES = frozenset({"provider", "recommendation", "community"})


def normalize_media_title(value: str | None) -> str:
    """Normalize punctuation and spacing for conservative, exact-title matching."""
    return re.sub(r"\W+", " ", str(value or "").casefold()).strip()


def safe_media_url(value: str | None) -> str | None:
    """Return a provider/source HTTPS URL, refusing credentials and non-web schemes."""
    value = str(value or "").strip()
    if not value:
        return None
    parsed = urlsplit(value)
    if parsed.scheme.lower() != "https" or not parsed.hostname or parsed.username or parsed.password:
        return None
    return value


def _category(value: str | None) -> str:
    normalized = re.sub(r"[\s-]+", "_", str(value or "").strip().upper())
    aliases = {
        "NOVEL": "LIGHT_NOVEL",
        "LIGHTNOVEL": "LIGHT_NOVEL",
        "LIGHT_NOVELS": "LIGHT_NOVEL",
        "BOOKS": "BOOK",
        "BOOK_/_NOVEL": "BOOK",
        "GENERAL_NOVEL": "BOOK",
        "MOVIES": "MOVIE",
        "TV_SERIES": "TV",
        "TELEVISION": "TV",
        "MANGA_/_MANHWA_/_MANHUA": "MANGA",
        "WEBNOVELS": "WEBNOVEL",
    }
    return aliases.get(normalized, normalized)


async def ensure_media_graph_schema() -> None:
    """Initialize the relationship table and indexes once per process."""
    global _SCHEMA_READY
    if _SCHEMA_READY:
        return
    async with _SCHEMA_LOCK:
        if _SCHEMA_READY:
            return
        statements = (
            (
                "create cross-media relationship graph",
                """CREATE TABLE IF NOT EXISTS media_relationship_graph (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    source_title VARCHAR(256) NOT NULL,
                    source_title_key VARCHAR(256) NOT NULL,
                    source_category VARCHAR(32) NOT NULL,
                    source_url TEXT,
                    target_title VARCHAR(256) NOT NULL,
                    target_title_key VARCHAR(256) NOT NULL,
                    target_category VARCHAR(32) NOT NULL,
                    target_url TEXT,
                    relationship_type VARCHAR(64) NOT NULL,
                    source_kind VARCHAR(24) NOT NULL,
                    source_label VARCHAR(100) NOT NULL,
                    guild_id BIGINT,
                    evidence TEXT,
                    created_by BIGINT,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                )""",
            ),
            (
                "index cross-media graph source lookups",
                "CREATE INDEX IF NOT EXISTS media_relationship_graph_source_idx ON media_relationship_graph (source_title_key, source_category, created_at DESC)",
            ),
            (
                "index cross-media graph target lookups",
                "CREATE INDEX IF NOT EXISTS media_relationship_graph_target_idx ON media_relationship_graph (target_title_key, target_category, created_at DESC)",
            ),
            (
                "index cross-media graph guild visibility",
                "CREATE INDEX IF NOT EXISTS media_relationship_graph_guild_idx ON media_relationship_graph (guild_id, source_kind, created_at DESC)",
            ),
            (
                "deduplicate cross-media graph relationships",
                """CREATE UNIQUE INDEX IF NOT EXISTS media_relationship_graph_identity_idx
                   ON media_relationship_graph (
                       source_title_key, source_category, COALESCE(source_url, ''),
                       target_title_key, target_category, COALESCE(target_url, ''),
                       relationship_type, source_kind, COALESCE(guild_id, 0)
                   )""",
            ),
        )
        for name, statement in statements:
            await database.execute_db_operation(name, statement)
        _SCHEMA_READY = True


async def record_media_relationship(
    source_title: str,
    source_category: str,
    source_url: str | None,
    target_title: str,
    target_category: str,
    target_url: str | None,
    relationship_type: str,
    *,
    source_kind: str,
    source_label: str,
    guild_id: int | None = None,
    evidence: str | None = None,
    created_by: int | None = None,
) -> bool:
    """Persist one edge; community edges cannot be written without a guild scope."""
    source_title = " ".join(str(source_title or "").split())[:256]
    target_title = " ".join(str(target_title or "").split())[:256]
    source_key = normalize_media_title(source_title)
    target_key = normalize_media_title(target_title)
    source_category = _category(source_category)
    target_category = _category(target_category)
    relationship_type = " ".join(str(relationship_type or "related").replace("_", " ").split())[:64].casefold()
    source_kind = str(source_kind or "").strip().casefold()
    if (
        not source_title or not target_title or not source_key or not target_key
        or (source_key == target_key and source_category == target_category)
        or source_category not in {"ANIME", "MANGA", "LIGHT_NOVEL", "WEBNOVEL", "BOOK", "MOVIE", "TV", "GAME"}
        or target_category not in {"ANIME", "MANGA", "LIGHT_NOVEL", "WEBNOVEL", "BOOK", "MOVIE", "TV", "GAME"}
        or source_kind not in GRAPH_SOURCES
    ):
        return False
    if source_kind == "community":
        if guild_id is None:
            return False
    else:
        # Provider metadata and provider recommendations are globally reusable.
        guild_id = None

    await ensure_media_graph_schema()
    inserted = await database.execute_db_operation(
        "record cross-media relationship",
        """INSERT INTO media_relationship_graph
           (source_title, source_title_key, source_category, source_url,
            target_title, target_title_key, target_category, target_url,
            relationship_type, source_kind, source_label, guild_id, evidence, created_by)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
           ON CONFLICT DO NOTHING RETURNING id""",
        (
            source_title, source_key, source_category, safe_media_url(source_url),
            target_title, target_key, target_category, safe_media_url(target_url),
            relationship_type, source_kind, str(source_label or source_kind)[:100],
            guild_id, str(evidence or "")[:1500] or None, created_by,
        ),
        fetch_type="one",
    )
    return bool(inserted)


async def find_media_relationships(
    title: str,
    category: str,
    url: str | None,
    guild_id: int | None,
    *,
    limit: int = 12,
) -> list[dict]:
    """Return graph neighbors, including approved community edges from this guild only."""
    title_key = normalize_media_title(title)
    category = _category(category)
    if not title_key:
        return []
    await ensure_media_graph_schema()
    canonical_url = safe_media_url(url) or ""
    if guild_id is None:
        visibility = "guild_id IS NULL"
        params: list[object] = [title_key, category, canonical_url, canonical_url,
                                title_key, category, canonical_url, canonical_url, max(1, min(limit, 30))]
    else:
        visibility = "(guild_id IS NULL OR guild_id = ?)"
        params = [guild_id, title_key, category, canonical_url, canonical_url,
                  title_key, category, canonical_url, canonical_url, max(1, min(limit, 30))]
    rows = await database.execute_db_operation(
        "find cross-media graph neighbors",
        f"""SELECT source_title, source_title_key, source_category, source_url,
                   relationship_type, target_title, target_title_key, target_category, target_url,
                   source_kind, source_label
            FROM media_relationship_graph
            WHERE {visibility}
              AND (
                (source_title_key = ? AND source_category = ? AND (? = '' OR source_url = ?))
                OR
                (target_title_key = ? AND target_category = ? AND (? = '' OR target_url = ?))
              )
            ORDER BY CASE source_kind WHEN 'provider' THEN 0 WHEN 'recommendation' THEN 1 ELSE 2 END,
                     created_at DESC
            LIMIT ?""",
        tuple(params),
        fetch_type="all",
    ) or []
    results = []
    seen = set()
    for row in rows:
        source_match = (
            row[1] == title_key and row[2] == category
            and (not canonical_url or row[3] == canonical_url)
        )
        related_title = row[5] if source_match else row[0]
        related_category = row[7] if source_match else row[2]
        related_url = row[8] if source_match else row[3]
        relation = str(row[4] or "related").replace("_", " ").title()
        if not source_match:
            relation = f"Incoming: {relation}"
        source_kind = str(row[9] or "provider")
        source_label = str(row[10] or "Metadata source")
        if source_kind == "community":
            relation = f"Community-verified: {relation}"
        elif source_kind == "recommendation":
            relation = f"Recommendation: {relation}"
        key = (normalize_media_title(related_title), related_category, related_url or "", relation)
        if key in seen or not related_title:
            continue
        seen.add(key)
        results.append({
            "title": str(related_title),
            "url": safe_media_url(related_url),
            "type": related_category,
            "relationType": relation,
            "source": source_label,
            "source_kind": source_kind,
        })
    return results


async def _safe_rows(operation: str, query: str, params: tuple = ()) -> list:
    """Read optional subsystem tables without taking down unrelated media commands."""
    try:
        return await database.execute_db_operation(operation, query, params, fetch_type="all") or []
    except Exception:
        log.debug("Optional cross-system lookup unavailable: %s", operation, exc_info=True)
        return []


async def find_linked_resources(
    title: str,
    category: str,
    guild_id: int | None,
    *,
    media_id: int | None = None,
    url: str | None = None,
    limit: int = 8,
) -> list[dict]:
    """Join a media title to existing Panels, public archives and this guild's events."""
    title = " ".join(str(title or "").split())
    title_key = normalize_media_title(title)
    if not title_key:
        return []
    safe_url = safe_media_url(url)
    pattern = f"%{title[:100]}%"
    jobs = [
        _safe_rows(
            "find related approved community archive entries",
            """SELECT id, archive_type, title, source_title, source_url, tags
               FROM community_archive_entries
               WHERE status = 'approved'
                 AND (COALESCE(source_title, '') ILIKE ? OR title ILIKE ?)
                 AND tags NOT ILIKE '%"nsfw"%' AND tags NOT ILIKE '%"mature"%'
               ORDER BY created_at DESC LIMIT 100""",
            (pattern, pattern),
        )
    ]
    job_names = ["archives"]
    if media_id and _category(category) in {"MANGA", "LIGHT_NOVEL"}:
        jobs.append(_safe_rows(
            "find related safe manga panels by AniList identity",
            """SELECT id, title, chapter_number, uploader_guild_id, storage_channel_id, storage_message_id, attachment_url, media_asset_id
               FROM panels
               WHERE is_nsfw = FALSE AND (anilist_id = ? OR LOWER(title) = LOWER(?))
               ORDER BY created_at DESC LIMIT 40""",
            (media_id, title),
        ))
        job_names.append("panels")
    else:
        jobs.append(_safe_rows(
            "find related safe manga panels by exact title",
            """SELECT id, title, chapter_number, uploader_guild_id, storage_channel_id, storage_message_id, attachment_url, media_asset_id
               FROM panels
               WHERE is_nsfw = FALSE AND LOWER(title) = LOWER(?)
               ORDER BY created_at DESC LIMIT 40""",
            (title,),
        ))
        job_names.append("panels")
    if guild_id is not None:
        jobs.extend((
            _safe_rows(
                "find same-guild media discussions",
                """SELECT guild_id, channel_id, thread_id, title, reference
                   FROM connected_media_discussions
                   WHERE guild_id = ? AND (LOWER(title) = LOWER(?) OR LOWER(reference) = LOWER(?))
                   ORDER BY created_at DESC LIMIT 20""",
                (guild_id, title, title),
            ),
            _safe_rows(
                "find same-guild adaptation polls",
                """SELECT poll_id, title, option_a, option_b
                   FROM community_adaptation_polls
                   WHERE guild_id = ?
                     AND (LOWER(title) = LOWER(?) OR LOWER(option_a) = LOWER(?) OR LOWER(option_b) = LOWER(?))
                   ORDER BY created_at DESC LIMIT 20""",
                (guild_id, title, title, title),
            ),
            _safe_rows(
                "find same-guild media quiz questions by source URL",
                """SELECT id FROM community_media_quiz_questions
                   WHERE guild_id = ? AND source_url = ?
                   ORDER BY created_at DESC LIMIT 10""",
                (guild_id, safe_url or ""),
            ),
            _safe_rows(
                "find same-guild media brackets",
                """SELECT bracket_id, title
                   FROM community_media_brackets
                   WHERE guild_id = ? AND LOWER(title) = LOWER(?)
                   ORDER BY created_at DESC LIMIT 20""",
                (guild_id, title),
            ),
        ))
        job_names.extend(("discussions", "polls", "quizzes", "brackets"))
        if safe_url:
            jobs.append(_safe_rows(
                "find same-guild linked media discussions by source URL",
                """SELECT guild_id, channel_id, thread_id, title, reference
                   FROM connected_media_discussions
                   WHERE guild_id = ? AND source_url = ?
                   ORDER BY created_at DESC LIMIT 10""",
                (guild_id, safe_url),
            ))
            job_names.append("discussions_by_url")
        jobs.append(_safe_rows(
            "find same-guild reading-club nominations",
            """SELECT nomination_id, title, category, source_url, status, thread_id
               FROM reading_club_nominations
               WHERE guild_id = ? AND status IN ('open', 'selected') AND LOWER(title) = LOWER(?)
               ORDER BY created_at DESC LIMIT 10""",
            (guild_id, title),
        ))
        job_names.append("reading_club")
        jobs.append(_safe_rows(
            "find same-guild active media-night candidates",
            """SELECT session_id, channel_id, message_id, category, candidates
               FROM media_night_sessions
               WHERE guild_id = ? AND status = 'open' AND expires_at > CURRENT_TIMESTAMP
               ORDER BY created_at DESC LIMIT 25""",
            (guild_id,),
        ))
        job_names.append("media_night")
    responses = await asyncio.gather(*jobs)
    response_map = dict(zip(job_names, responses))
    resources: list[dict] = []
    seen: set[tuple] = set()

    def add(kind: str, label: str, resource_url: str | None, source: str) -> None:
        label = " ".join(str(label or "").split())[:180]
        target_url = safe_media_url(resource_url)
        key = (kind, normalize_media_title(label), target_url or "")
        if not label or key in seen:
            return
        seen.add(key)
        resources.append({"kind": kind, "title": label, "url": target_url, "source": source})

    for row in response_map.get("archives", []):
        if normalize_media_title(row[3]) != title_key and normalize_media_title(row[2]) != title_key:
            continue
        archive_type = str(row[1] or "archive").replace("-", " ").title()
        add(f"Community {archive_type}", f"{row[2]} · #{row[0]}", row[4], f"Shared /{str(row[1] or 'archive')} archive")
    for row in response_map.get("panels", []):
        if normalize_media_title(row[1]) != title_key and not (media_id and _category(category) in {"MANGA", "LIGHT_NOVEL"}):
            continue
        panel_url = None
        if row[3] and row[4] and row[5]:
            panel_url = f"https://discord.com/channels/{int(row[3])}/{int(row[4])}/{int(row[5])}"
        elif row[7]:
            try:
                panel_url = await media_storage.asset_url(int(row[7]))
            except Exception:
                log.debug("Could not sign linked panel asset %s", row[7], exc_info=True)
        elif row[6]:
            panel_url = safe_media_url(row[6])
        label = f"Panel #{row[0]}" + (f" · Chapter {row[2]}" if row[2] else "") + f" · {row[1]}"
        add("Manga panel", label, panel_url, "Shared Panels archive · safe entries only")
    for rows in (response_map.get("discussions", []), response_map.get("discussions_by_url", [])):
        for row in rows:
            resource_url = f"https://discord.com/channels/{int(row[0])}/{int(row[2])}" if row[0] and row[2] else None
            add("Discussion", f"{row[3]} · {row[4]}", resource_url, "This server's connected discussion")
    for row in response_map.get("polls", []):
        add("Adaptation poll", f"{row[1]} · #{row[0]}", None, "This server's adaptation votes")
    for row in response_map.get("quizzes", []):
        add("Media quiz", f"Quiz question · #{row[0]}", None, "This server's source-linked media quiz")
    for row in response_map.get("brackets", []):
        add("Media bracket", f"{row[1]} · #{row[0]}", None, "This server's media bracket")

    for row in response_map.get("reading_club", []):
        if normalize_media_title(row[1]) != title_key:
            continue
        resource_url = f"https://discord.com/channels/{int(guild_id)}/{int(row[5])}" if row[5] else row[3]
        add(
            "Reading Club",
            f"{row[1]} · {row[2]} · {str(row[4]).title()} · #{row[0]}",
            resource_url,
            "This server's reading-club nomination",
        )

    for row in response_map.get("media_night", []):
        try:
            candidates = json.loads(row[4] or "[]")
        except (TypeError, ValueError):
            continue
        if not isinstance(candidates, list):
            continue
        for candidate in candidates:
            if not isinstance(candidate, dict):
                continue
            candidate_title = candidate.get("title") or candidate.get("name") or ""
            if isinstance(candidate_title, dict):
                candidate_title = candidate_title.get("english") or candidate_title.get("romaji") or candidate_title.get("native") or ""
            if normalize_media_title(str(candidate_title)) != title_key:
                continue
            resource_url = f"https://discord.com/channels/{int(guild_id)}/{int(row[1])}/{int(row[2])}" if row[1] and row[2] else None
            add(
                "Media Night",
                f"{candidate_title} · {row[3]} · Session #{row[0]}",
                resource_url,
                "This server's active media-night vote",
            )
            break
    return resources[:max(1, min(limit, 12))]


async def find_community_recommendations(
    seed_title: str,
    genres: list[str] | None,
    tags: list[str] | None,
    *,
    limit: int = 5,
) -> list[dict]:
    """Find approved human-written recommendations sharing explicit provider tags."""
    seed_key = normalize_media_title(seed_title)
    seed_tags = {
        normalize_media_title(value)
        for value in [*(genres or []), *(tags or [])]
        if normalize_media_title(value)
    }
    if not seed_tags:
        return []
    rows = await _safe_rows(
        "find relevant community recommendation-board entries",
        """SELECT id, title, content, source_title, media_type, source_url, tags, spoiler
           FROM community_archive_entries
           WHERE archive_type = 'recommendation-board' AND status = 'approved'
             AND tags NOT ILIKE '%"nsfw"%' AND tags NOT ILIKE '%"mature"%'
           ORDER BY created_at DESC LIMIT 100""",
    )
    matches = []
    for row in rows:
        if normalize_media_title(row[1]) == seed_key:
            continue
        try:
            entry_tags = json.loads(row[6] or "[]")
        except (TypeError, ValueError):
            continue
        if not isinstance(entry_tags, list):
            continue
        shared = sorted({
            normalize_media_title(tag) for tag in entry_tags
            if normalize_media_title(tag) in seed_tags
        })
        if not shared:
            continue
        matches.append({
            "title": str(row[1] or "Untitled"),
            "content": f"||{str(row[2] or '')}||" if bool(row[7]) else str(row[2] or ""),
            "url": safe_media_url(row[5]),
            "category": str(row[4] or "Other"),
            "source_title": str(row[3] or ""),
            "shared": shared,
            "source": f"Human-written community recommendation · #{row[0]}",
        })
    matches.sort(key=lambda item: (-len(item["shared"]), item["title"].casefold()))
    return matches[:max(1, min(limit, 10))]
