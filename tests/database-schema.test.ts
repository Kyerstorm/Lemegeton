import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { Pool } from "pg";
import { closeDatabase, initDatabase, query, queryOne } from "../database.js";
import type { DatabaseConfig } from "../helpers/runtime/config.js";

const databaseUrl = process.env.TEST_DATABASE_URL?.trim();

test("PostgreSQL initialization preserves legacy guild data and is repeatable", {
  skip: databaseUrl ? false : "TEST_DATABASE_URL is not configured",
}, async () => {
  assert.ok(databaseUrl);
  const admin = new Pool({ connectionString: databaseUrl });
  const schema = "lemegeton_migration_" + randomUUID().replaceAll("-", "");

  try {
    await admin.query(`CREATE SCHEMA "${schema}"`);

    await admin.query(`
      CREATE TABLE "${schema}".steam_users (
        discord_id BIGINT NOT NULL PRIMARY KEY,
        steam_id TEXT NOT NULL,
        vanity_name TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);
    await admin.query(
      `INSERT INTO "${schema}".steam_users (discord_id, steam_id, vanity_name)
       VALUES ($1, $2, $3)`,
      ["76561198000000000", "76561198000000000", "legacy-player"],
    );

    await admin.query(`
      CREATE TABLE "${schema}".booster_roles (
        discord_id INTEGER NOT NULL,
        guild_id INTEGER NOT NULL,
        role_id INTEGER NOT NULL,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (discord_id, guild_id)
      )
    `);
    await admin.query(
      `INSERT INTO "${schema}".booster_roles (discord_id, guild_id, role_id)
       VALUES (101, 202, 303)`,
    );

    await admin.query(`
      CREATE TABLE "${schema}".bot_moderators (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        discord_id INTEGER NOT NULL UNIQUE,
        username TEXT NOT NULL,
        added_by INTEGER NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);
    await admin.query(
      `INSERT INTO "${schema}".bot_moderators (discord_id, username, added_by)
       VALUES (101, 'legacy-moderator', 202)`,
    );

    await admin.query(`
      CREATE TABLE "${schema}".custom_role_records (
        guild_id INTEGER NOT NULL,
        user_id INTEGER NOT NULL,
        role_id INTEGER,
        icon_source_asset_id INTEGER,
        PRIMARY KEY (guild_id, user_id)
      )
    `);
    await admin.query(
      `INSERT INTO "${schema}".custom_role_records (guild_id, user_id, role_id, icon_source_asset_id)
       VALUES (303, 404, 505, 606)`,
    );

    await admin.query(`
      CREATE TABLE "${schema}".custom_role_guild_settings (
        guild_id INTEGER PRIMARY KEY,
        anchor_role_id INTEGER,
        command_channel_id INTEGER,
        log_channel_id INTEGER
      )
    `);
    await admin.query(
      `INSERT INTO "${schema}".custom_role_guild_settings (guild_id, anchor_role_id, command_channel_id, log_channel_id)
       VALUES (707, 808, 909, 1001)`,
    );
    await admin.query(`
      CREATE TABLE "${schema}".custom_role_archive_snoozes (
        guild_id INTEGER NOT NULL,
        user_id INTEGER NOT NULL,
        until TIMESTAMP NOT NULL,
        PRIMARY KEY (guild_id, user_id)
      )
    `);
    await admin.query(
      `INSERT INTO "${schema}".custom_role_archive_snoozes (guild_id, user_id, until)
       VALUES (1101, 1201, NOW() + INTERVAL '1 day')`,
    );

    await admin.query(`
      CREATE TABLE "${schema}".custom_role_pending_removals (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id INTEGER NOT NULL,
        user_ids TEXT NOT NULL DEFAULT '[]',
        reason TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'pending',
        log_channel_id INTEGER,
        log_message_id INTEGER,
        resolved_by INTEGER,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        resolved_at TIMESTAMP
      )
    `);
    const pendingId = (await admin.query(
      `INSERT INTO "${schema}".custom_role_pending_removals (guild_id, user_ids, reason)
       VALUES ($1, $2, $3) RETURNING id`,
      ["404", JSON.stringify(["111111111111111111"]), "legacy pending removal"],
    )).rows[0].id as string;

    const scopedUrl = new URL(databaseUrl);
    scopedUrl.searchParams.set("options", "-c search_path=" + schema);
    const parsedUrl = new URL(databaseUrl);
    const config: DatabaseConfig = {
      connectionString: scopedUrl.toString(),
      host: parsedUrl.hostname,
      port: Number(parsedUrl.port || 5432),
      database: decodeURIComponent(parsedUrl.pathname.replace(/^\//, "")),
      user: decodeURIComponent(parsedUrl.username),
      password: decodeURIComponent(parsedUrl.password),
      ssl: false,
      poolSize: 2,
      primaryGuildId: "987654321098765432",
    };

    await initDatabase(config);

    const steam = await queryOne<{ guild_id: string; steam_id: string }>(
      "SELECT guild_id, steam_id FROM steam_users WHERE discord_id = $1",
      ["76561198000000000"],
    );
    assert.deepEqual(steam, {
      guild_id: "987654321098765432",
      steam_id: "76561198000000000",
    });

    const steamColumns = await query<{ column_name: string; data_type: string }>(
      `SELECT column_name, data_type FROM information_schema.columns
       WHERE table_schema = current_schema() AND table_name = 'steam_users'`,
    );
    assert.equal(steamColumns.find(column => column.column_name === "guild_id")?.data_type, "bigint");

    const steamPrimaryKey = await query<{ column_name: string; ordinal_position: number }>(
      `SELECT column_name, ordinal_position FROM information_schema.key_column_usage
       WHERE table_schema = current_schema() AND table_name = 'steam_users'
         AND constraint_name = (
           SELECT constraint_name FROM information_schema.table_constraints
           WHERE table_schema = current_schema() AND table_name = 'steam_users'
             AND constraint_type = 'PRIMARY KEY'
         )
       ORDER BY ordinal_position`,
    );
    assert.deepEqual(steamPrimaryKey.map(column => column.column_name), ["discord_id", "guild_id"]);

    const boosterColumns = await query<{ column_name: string; data_type: string }>(
      `SELECT column_name, data_type FROM information_schema.columns
       WHERE table_schema = current_schema() AND table_name = 'booster_roles'`,
    );
    for (const column of ["discord_id", "guild_id", "role_id"]) {
      assert.equal(boosterColumns.find(item => item.column_name === column)?.data_type, "bigint");
    }
    assert.deepEqual(
      await queryOne<{ role_id: string }>(
        "SELECT role_id FROM booster_roles WHERE discord_id = $1 AND guild_id = $2",
        [101, 202],
      ),
      { role_id: "303" },
    );

    const migratedIdentifierColumns = await query<{
      table_name: string;
      column_name: string;
      data_type: string;
    }>(
      `SELECT table_name, column_name, data_type FROM information_schema.columns
       WHERE table_schema = current_schema() AND (
         (table_name = 'bot_moderators' AND column_name IN ('discord_id','added_by')) OR
         (table_name = 'custom_role_records' AND column_name IN ('guild_id','user_id','role_id','icon_source_asset_id')) OR
         (table_name = 'custom_role_guild_settings' AND column_name IN ('guild_id','anchor_role_id','command_channel_id','log_channel_id')) OR
         (table_name = 'custom_role_pending_removals' AND column_name IN ('guild_id','log_channel_id','log_message_id','resolved_by')) OR
         (table_name = 'custom_role_archive_snoozes' AND column_name IN ('guild_id','user_id'))
       )`,
    );
    assert.equal(migratedIdentifierColumns.length, 16);
    assert.ok(migratedIdentifierColumns.every(column => column.data_type === "bigint"));

    assert.deepEqual(
      await queryOne<{ username: string; added_by: string }>(
        "SELECT username, added_by FROM bot_moderators WHERE discord_id = $1",
        [101],
      ),
      { username: "legacy-moderator", added_by: "202" },
    );
    assert.deepEqual(
      await queryOne<{ role_id: string; icon_source_asset_id: string }>(
        "SELECT role_id, icon_source_asset_id FROM custom_role_records WHERE guild_id = $1 AND user_id = $2",
        [303, 404],
      ),
      { role_id: "505", icon_source_asset_id: "606" },
    );
    assert.deepEqual(
      await queryOne<{ anchor_role_id: string; command_channel_id: string; log_channel_id: string }>(
        "SELECT anchor_role_id, command_channel_id, log_channel_id FROM custom_role_guild_settings WHERE guild_id = $1",
        [707],
      ),
      { anchor_role_id: "808", command_channel_id: "909", log_channel_id: "1001" },
    );
    assert.deepEqual(
      await queryOne<{ guild_id: string; user_id: string }>(
        "SELECT guild_id, user_id FROM custom_role_archive_snoozes WHERE guild_id = $1 AND user_id = $2",
        [1101, 1201],
      ),
      { guild_id: "1101", user_id: "1201" },
    );

    const pendingUserIdsColumn = await queryOne<{ data_type: string }>(
      `SELECT data_type FROM information_schema.columns
       WHERE table_schema = current_schema() AND table_name = 'custom_role_pending_removals'
         AND column_name = 'user_ids'`,
    );
    assert.deepEqual(pendingUserIdsColumn, { data_type: "jsonb" });
    const pendingUserIdsDefault = await queryOne<{ column_default: string }>(
      `SELECT column_default FROM information_schema.columns
       WHERE table_schema = current_schema() AND table_name = 'custom_role_pending_removals'
         AND column_name = 'user_ids'`,
    );
    assert.deepEqual(pendingUserIdsDefault, { column_default: "'[]'::jsonb" });
    assert.deepEqual(
      await queryOne<{ user_ids: string[] }>(
        "SELECT user_ids FROM custom_role_pending_removals WHERE id = $1",
        [pendingId],
      ),
      { user_ids: ["111111111111111111"] },
    );
    await query(
      "UPDATE custom_role_pending_removals SET user_ids = $2::jsonb WHERE id = $1",
      [pendingId, JSON.stringify(["111111111111111111", "222222222222222222"])],
    );
    assert.deepEqual(
      await queryOne<{ user_ids: string[] }>(
        "SELECT user_ids FROM custom_role_pending_removals WHERE id = $1",
        [pendingId],
      ),
      { user_ids: ["111111111111111111", "222222222222222222"] },
    );

    await query(
      `INSERT INTO users (discord_id, guild_id, username)
       VALUES ($1, $2, $3), ($1, $4, $5)`,
      ["111111111111111111", "222222222222222222", "same-member", "333333333333333333", "same-member"],
    );
    assert.equal(
      (await query("SELECT discord_id FROM users WHERE discord_id = $1", ["111111111111111111"])).length,
      2,
    );
    await assert.rejects(
      query(
        "INSERT INTO users (discord_id, guild_id, username) VALUES ($1, $2, $3)",
        ["111111111111111111", "222222222222222222", "duplicate"],
      ),
      /users_discord_guild_idx|users_discord_id_guild_id_key|duplicate key/i,
    );

    await assert.rejects(
      query(
        `INSERT INTO issue_logs
          (issue_hash, guild_id, user_id, username, interaction_id, command_name)
         VALUES ($1, $2, $3, $4, $5, $6)`,
        ["a".repeat(39), "222222222222222222", "111111111111111111", "member", "444444444444444444", "/discover"],
      ),
      /issue_logs_issue_hash_format_check|check constraint/i,
    );
    await query(
      `INSERT INTO issue_logs
        (issue_hash, guild_id, user_id, username, interaction_id, command_name)
       VALUES ($1, $2, $3, $4, $5, $6)`,
      ["a".repeat(40), "222222222222222222", "111111111111111111", "member", "444444444444444444", "/discover"],
    );

    await initDatabase(config);
    assert.deepEqual(
      await queryOne<{ count: string }>("SELECT COUNT(*)::text AS count FROM issue_logs"),
      { count: "1" },
    );
    assert.deepEqual(
      await queryOne<{ count: string }>("SELECT COUNT(*)::text AS count FROM steam_users"),
      { count: "1" },
    );
  } finally {
    await closeDatabase();
    await admin.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`).catch(() => undefined);
    await admin.end();
  }
});
