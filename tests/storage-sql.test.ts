import assert from "node:assert/strict";
import test from "node:test";
import { toLibSqlSql } from "../src/utility/database/libsql/sql.js";

test("translates PostgreSQL placeholders, casts, row locks and array membership", () => {
  assert.equal(
    toLibSqlSql("SELECT id::text FROM users WHERE guild_id = ANY($1::bigint[]) FOR UPDATE"),
    "SELECT id FROM users WHERE guild_id IN (SELECT value FROM json_each($1));",
  );
});

test("translates PostgreSQL timestamps and interval arithmetic", () => {
  assert.equal(toLibSqlSql("UPDATE jobs SET next_at = NOW() + INTERVAL '1 hour'"),
    "UPDATE jobs SET next_at = datetime(CURRENT_TIMESTAMP, '+1 hours');");
  assert.equal(toLibSqlSql("WHERE next_at <= NOW() - INTERVAL '24 hours'"),
    "WHERE next_at <= datetime(CURRENT_TIMESTAMP, '-24 hours');");
});

test("maps PostgreSQL schema types and identity columns to libSQL", () => {
  const sql = toLibSqlSql(
    "CREATE TABLE IF NOT EXISTS records (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, guild_id BIGINT NOT NULL, metadata JSONB NOT NULL DEFAULT '{}'::JSONB, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), payload BYTEA)",
    true,
  );
  assert.match(sql, /id INTEGER PRIMARY KEY AUTOINCREMENT/);
  assert.match(sql, /guild_id INTEGER NOT NULL/);
  assert.match(sql, /metadata TEXT NOT NULL DEFAULT '\{\}'/);
  assert.match(sql, /created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP/);
  assert.match(sql, /payload BLOB/);
});

test("keeps multi-guild identifier checks compatible with SQLite GLOB", () => {
  assert.equal(
    toLibSqlSql("SELECT guild_id FROM settings WHERE guild_id::text !~ '[^0-9]'"),
    "SELECT guild_id FROM settings WHERE guild_id NOT GLOB '*[^0-9]*';",
  );
});

test("translates PostgreSQL array-column membership and one-based array indexing", () => {
  assert.equal(
    toLibSqlSql("SELECT id FROM community_game_sessions WHERE $2::BIGINT = ANY(question_ids)"),
    "SELECT id FROM community_game_sessions WHERE EXISTS (SELECT 1 FROM json_each(question_ids) AS values_list WHERE values_list.value = $2);",
  );
  assert.equal(
    toLibSqlSql("SELECT q.id FROM sessions s JOIN questions q ON q.id = s.question_ids[s.current_round + 1]"),
    "SELECT q.id FROM sessions s JOIN questions q ON q.id = json_extract(s.question_ids, '$[' || s.current_round || ']');",
  );
});

test("removes PostgreSQL table-scoped row locks", () => {
  assert.equal(
    toLibSqlSql("SELECT q.id FROM questions q WHERE q.pack_id = $1 FOR SHARE OF q"),
    "SELECT q.id FROM questions q WHERE q.pack_id = $1;",
  );
  assert.equal(
    toLibSqlSql("SELECT id FROM jobs WHERE status = 'pending' FOR UPDATE OF jobs SKIP LOCKED"),
    "SELECT id FROM jobs WHERE status = 'pending';",
  );
});
